"""Rebuild Mataro's city design-rainfall (IDF) table from its sewer master plan, and verify it against the printed table.

Source: PDCLAM '03, "Pla Director de Clavegueram de Mataro", Document num. 1: Memoria, 71 pp.
        CLABSA for Aigues de Mataro, 2003. Gumbel quantiles Pd on Memoria p.26; IDF table p.28.
        https://oficinavirtual.aiguesmataro.com/api/doc/F2104/pla-dir-clavegueram
        No reuse licence is stated in the document: cite it, do not redistribute the PDF.
Method (as printed on Memoria p.28, MOPU 1990 Instruccion 5.2-IC in its original form):
        I(D) = (Pd / 24) * (I1/Id) ** ((28**0.1 - D**0.1) / 0.4),  D in hours, I1/Id = 11 for Catalonia.
        NB this is NOT the 2016 restatement of 5.2-IC, whose exponent is (3.5287 - 2.5287 * D**0.1);
        the two differ by ~3% and only the 1990 form reproduces the plan's own numbers.
Output: databases/mataro/mataro_idf_city.csv
"""
import pathlib, csv

ROOT = pathlib.Path(__file__).resolve().parents[1]
I1_ID = 11.0            # regional torrentiality factor, Catalonia; plan p.27 "en el nostre cas es igual a 11"

# Gumbel daily maxima, PDCLAM '03 Memoria p.26. T=1.001 is the plan's numerical stand-in for the
# undefined T=1 limit; the plan's IDF table heads that column "1", which is wrong and must not be used.
PD = {1.001: 13.4096, 2: 60.6091, 5: 83.8759, 10: 99.2804,
      50: 133.1835, 100: 147.5162, 500: 180.6369, 1000: 194.8760}

# Printed IDF table, Memoria p.28 (mm/h), used only to verify the formula reproduces the document.
PRINTED = {
    5:  [22.366, 101.091, 139.898, 165.591, 222.139, 246.044, 301.287, 325.036],
    10: [15.990, 72.271, 100.015, 118.383, 158.810, 175.900, 215.394, 232.373],
    20: [11.159, 50.438, 69.800, 82.619, 110.833, 122.760, 150.323, 162.172],
    30: [8.935, 40.386, 55.890, 66.155, 88.745, 98.296, 120.366, 129.854],
    60: [5.981, 27.033, 37.410, 44.280, 59.402, 65.794, 80.567, 86.917],
    120: [3.890, 17.580, 24.329, 28.797, 38.631, 42.789, 52.395, 56.526],
}
TS = list(PD)

def intensity(pd_mm, d_min):
    d_h = d_min / 60.0
    return (pd_mm / 24.0) * I1_ID ** ((28 ** 0.1 - d_h ** 0.1) / 0.4)

worst = 0.0
for d, row in PRINTED.items():
    for t, printed in zip(TS, row):
        worst = max(worst, abs(intensity(PD[t], d) / printed - 1))
print(f"max deviation from the printed table: {100 * worst:.4f}%  ({len(PRINTED) * len(TS)} cells)")

out = ROOT / "databases/mataro/mataro_idf_city.csv"
HEADER = """\
# Mataro city design rainfall (IDF). Source: PDCLAM '03 sewer master plan, Memoria pp. 26 and 28
# (CLABSA for Aigues de Mataro, 2003). Gumbel on annual daily maxima + MOPU 1990 Instruccion 5.2-IC,
# I1/Id = 11. Regenerated by scripts/make_mataro_idf.py, which reproduces the 48 printed cells to 0.011%.
# LIMITS: (1) T_years = 1.001 is the plan's stand-in for the undefined Gumbel T = 1 limit, NOT a 1-year
# rainfall - do not use it. No route gives T = 1 for any Catalan city. (2) This is a CENTRAL estimate from
# daily maxima compiled in 1993, assuming stationarity; Barcelona's PDISBA design column is an across-gauge
# ENVELOPE from pluviograph records with a climate uplift. Harmonise before comparing - see
# notes/catalan_transfer_city.md section 5b. (3) The sub-hourly shape is analytic, from one national
# 4-class constant; no sub-hourly observation from Mataro enters it. (4) No reuse licence is stated in
# the source document: cite it, do not redistribute the PDF.
"""

with out.open("w", newline="") as f:
    f.write(HEADER)
    w = csv.writer(f)
    w.writerow(["duration_min", "T_years", "Pd_mm", "intensity_mmh", "depth_mm", "note"])
    for d in range(5, 121, 5):
        for t in TS:
            # the plan prints this column as "T=1"; it is the Gumbel T=1.001 limit, 0.27-0.31x Barcelona's
            # T=1 intensities against 0.68-0.85x at T=2 and T=10. Not a 1-year storm. Do not use.
            note = "Gumbel T=1.001 limit, NOT a 1-year rainfall - do not use" if t == 1.001 else ""
            i = intensity(PD[t], d)
            w.writerow([d, t, f"{PD[t]:.4f}", f"{i:.3f}", f"{i * d / 60.0:.2f}", note])
print(f"wrote {out.relative_to(ROOT)}")
