"""Build thesis/references.bib from the citation keys used in thesis/0*.md.

Source of truth: thesis/bib_overrides.json (one entry per key, verified fields; "_check" records how).
A key cited in a chapter but missing from the overrides gets a fallback entry if its chapter
comment block names a literature-matrix row ("key  #id ..."): DOI from the matrix, title / first
author / venue / year from the cached OpenAlex search records (notes/lit/candidates*.csv,
shortlist.csv). Fallback entries are printed as "CHECK" and should be verified, then moved
into the overrides. No network calls.

Run from the repository root: python scripts/build_bib.py
"""
import csv
import glob
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LIT = ROOT / "notes/lit"
FIELDS = ("author", "title", "journal", "booktitle", "year", "date", "volume", "number", "pages",
          "doi", "url", "urldate", "howpublished", "note", "langid")
# Words citeproc must not lower-case when it sentence-cases English titles
PROPER = ("European", "Great Lakes", "L/tree", "San Juan", "Puerto Rico", "AI", "SylvCiT", "Karlsruhe",
          "Germany", "Florence", "Italy", "Tipuana", "Lisbon", "Portugal", "Mediterranean", "London",
          "Platanus", "Davis", "California", "UTCI", "INFRARED", "Vienna", "Barcelona", "Jacaranda",
          "D. Don.", "BBCH", "Sardon", "Spain")


def protect(title):
    for w in PROPER:
        title = re.sub(rf"(?<![{{\w]){re.escape(w)}(?![\w}}])", "{" + w + "}", title)
    return title


def used_keys():
    keys, blocks = set(), {}
    for f in sorted(glob.glob(str(ROOT / "thesis/0*.md"))):
        text = Path(f).read_text(encoding="utf-8")
        body = re.sub(r"<!--.*?-->", "", text, flags=re.S)
        keys |= {k for k in re.findall(r"(?<![\w.])@([A-Za-z0-9][\w-]*[A-Za-z0-9])(?![\w:-])", body)}
        for c in re.findall(r"<!--(.*?)-->", text, flags=re.S):
            for line in c.splitlines():
                m = re.match(r"^([a-z0-9]\w+)\s{2,}#(\d+)", line)
                if m:
                    blocks[m.group(1)] = m.group(2)
    return keys, blocks


def fallback(mid):
    rows = {r["id"]: r for r in csv.DictReader(open(LIT / "literature_matrix.csv", encoding="utf-8"))}
    doi = rows.get(mid, {}).get("doi", "").strip().lower()
    if not doi:
        return None
    for f in ("candidates.csv", "candidates_2.csv", "candidates_heat.csv", "shortlist.csv"):
        for r in csv.DictReader(open(LIT / f, encoding="utf-8")):
            if r["doi"].lower().replace("https://doi.org/", "") == doi:
                return {"type": "article", "author": f"{r['first_author']} and others", "title": r["title"],
                        "journal": r["venue"], "year": r["year"], "doi": doi, "_check": "FALLBACK"}
    return {"type": "misc", "title": rows[mid]["citation"], "doi": doi, "_check": "FALLBACK"}


def bib(key, e):
    lines = [f"@{e['type']}{{{key},"]
    for f in FIELDS:
        v = e.get(f)
        if not v:
            continue
        if f == "title" and not e.get("langid"):
            v = protect(v)
        if f == "booktitle":
            v = "{" + v + "}"
        lines.append(f"  {f} = {{{v}}},")
    return "\n".join(lines) + "\n}\n"


def main():
    over = json.load(open(ROOT / "thesis/bib_overrides.json", encoding="utf-8"))
    keys, blocks = used_keys()
    out, missing = [], []
    for k in sorted(keys):
        e = over.get(k) or (fallback(blocks[k]) if k in blocks else None)
        if e is None:
            missing.append(k)
            continue
        if e["_check"] == "FALLBACK":
            print("CHECK", k)
        out.append(bib(k, e))
    (ROOT / "thesis/references.bib").write_text(
        "% Generated by scripts/build_bib.py from thesis/bib_overrides.json; do not edit by hand.\n\n"
        + "\n".join(out), encoding="utf-8")
    print(f"{len(out)} entries written; missing: {missing or 'none'}")


if __name__ == "__main__":
    main()
